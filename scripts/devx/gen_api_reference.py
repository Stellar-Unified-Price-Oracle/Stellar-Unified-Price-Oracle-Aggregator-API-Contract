#!/usr/bin/env python3
"""Generate the API reference markdown from interface/interface.json (issue #853).

Usage:
  gen_api_reference.py            regenerate docs/api-reference.md
  gen_api_reference.py --check    CI: fail if the committed reference is stale
"""
import json, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
IFACE = ROOT / "interface/interface.json"
OUT = ROOT / "docs/api-reference.md"

HEADER = """<!-- Generated by scripts/devx/gen_api_reference.py from interface/interface.json. Do not edit by hand. -->

# API Reference

Contract: `{contract}` · Interface version: `{version}` · Package: `{name}`

This reference is generated from [`interface/interface.json`](../interface/interface.json).
Regenerate with `python3 scripts/devx/gen_api_reference.py`; CI fails when it is stale.

## Functions

| Function | Parameters | Returns |
|---|---|---|
"""


def cell(text):
    return str(text).replace("|", "\\|")


def render(art):
    rows = []
    for name, fn in art["functions"].items():
        params = fn.get("params") or []
        params = "<br>".join(f"`{cell(p)}`" for p in params) if params else "—"
        rows.append(f"| `{name}` | {params} | `{cell(fn.get('returns', '()'))}` |")
    return HEADER.format(
        contract=art["contract"], version=art["version"], name=art["name"]
    ) + "\n".join(rows) + "\n"


def main():
    art = json.loads(IFACE.read_text())
    text = render(art)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                "docs/api-reference.md is stale; run scripts/devx/gen_api_reference.py",
                file=sys.stderr,
            )
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"api reference {art['version']}: {len(art['functions'])} functions")


if __name__ == "__main__":
    main()
