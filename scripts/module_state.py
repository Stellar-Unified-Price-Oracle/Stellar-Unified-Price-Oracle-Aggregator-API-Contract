#!/usr/bin/env python3
"""Report whether the reputation, correlation, tiered-whitelisting and
alert-subscription modules (and their test files) are compiled into the
`price-oracle` crate.

A module counts as *compiled* when `contracts/price-oracle/src/lib.rs`
declares it with `mod <name>;`. A test file counts as *compiled* when it is
declared (normally behind `#[cfg(test)]`). The script writes
`docs/code-health/module-state.md`, or exits non-zero with `--check` when the
checked-in report is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "contracts" / "price-oracle" / "src"
LIB = SRC / "lib.rs"
OUT = ROOT / "docs" / "code-health" / "module-state.md"

# group -> (modules, test files)
GROUPS = {
    "Reputation": (["reputation"], ["reputation_gaming_tests"]),
    "Correlation": (["correlation"], ["correlation_feature_tests"]),
    "Tiered whitelisting": (["whitelisting"], ["whitelist_tests"]),
    "Alert subscription": (
        ["alerting", "alerts", "alert_severity", "subscription", "price_update_subscription"],
        ["issue_307_alert_rules_tests"],
    ),
}

MOD_RE = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;", re.M)
CFG_TEST_MOD_RE = re.compile(r"#\[cfg\(test\)\]\s*(?:#\[[^\]]*\]\s*)*(?:pub\s+)?mod\s+(\w+)\s*;")
TEST_RE = re.compile(r"#\[test\]")
PUB_FN_RE = re.compile(r"^\s*pub\s+(?:const\s+)?fn\s+\w+", re.M)


def declared_modules() -> tuple[set[str], set[str]]:
    text = LIB.read_text(encoding="utf-8")
    return set(MOD_RE.findall(text)), set(CFG_TEST_MOD_RE.findall(text))


def line_count(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def render() -> str:
    declared, cfg_test = declared_modules()
    out = [
        "# Module state: reputation, correlation, tiered whitelisting, alert subscription",
        "",
        "Generated by `scripts/module_state.py` from `contracts/price-oracle/src/lib.rs`.",
        "Do not edit by hand; re-run the script after wiring or removing a module.",
        "",
        "| Group | Module file | Lines | Public fns | Compiled (`mod` in `lib.rs`) |",
        "|---|---|---:|---:|---|",
    ]
    findings = []
    for group, (mods, tests) in GROUPS.items():
        for m in mods:
            path = SRC / f"{m}.rs"
            if not path.exists():
                out.append(f"| {group} | `{m}.rs` | — | — | **file missing** |")
                findings.append(f"`{m}.rs` does not exist.")
                continue
            text = path.read_text(encoding="utf-8")
            ok = m in declared
            out.append(
                f"| {group} | `{m}.rs` | {line_count(path)} | {len(PUB_FN_RE.findall(text))} | "
                f"{'yes' if ok else '**NO**'} |"
            )
            if not ok:
                findings.append(f"`{m}.rs` exists but is not declared in `lib.rs`.")
    out += [
        "",
        "| Group | Test file | `#[test]` fns | Compiled | Behind `#[cfg(test)]` |",
        "|---|---|---:|---|---|",
    ]
    for group, (_, tests) in GROUPS.items():
        for t in tests:
            path = SRC / f"{t}.rs"
            if not path.exists():
                out.append(f"| {group} | `{t}.rs` | — | **file missing** | — |")
                findings.append(f"`{t}.rs` does not exist.")
                continue
            n = len(TEST_RE.findall(path.read_text(encoding="utf-8")))
            ok = t in declared
            out.append(
                f"| {group} | `{t}.rs` | {n} | {'yes' if ok else '**NO**'} | "
                f"{'yes' if t in cfg_test else 'no'} |"
            )
            if not ok:
                findings.append(
                    f"`{t}.rs` ({n} tests) exists but is not declared in `lib.rs`, so its tests never run."
                )
    out += ["", "## Findings", ""]
    out += [f"- {f}" for f in findings] or ["- Every listed module and test file is compiled."]
    out.append("")
    return "\n".join(out)


def main() -> int:
    report = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != report:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/module_state.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(report, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
