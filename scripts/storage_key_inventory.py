#!/usr/bin/env python3
"""Enumerate every `DataKey` variant and the storage tier it is written to.

The script parses the `DataKey` enum in `contracts/price-oracle/src/types.rs`
and scans the non-test sources under `contracts/price-oracle/src` for storage
writes (`.set(` / `.extend_ttl(`) that go through
`env.storage().instance() | .persistent() | .temporary()`. For every variant it
records the tier(s) it is written to and the files that write it, and renders
`docs/storage-key-inventory.md`.

Detection is textual, so it is deliberately conservative: a variant whose key
is built in one place and written in another is attributed through the nearest
preceding `let <name> = DataKey::Variant...` binding. Variants for which no
write could be attributed are reported as `unresolved` rather than guessed.

Usage:
    python3 scripts/storage_key_inventory.py          # (re)write the doc
    python3 scripts/storage_key_inventory.py --check  # exit 1 if the doc is stale
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "contracts" / "price-oracle" / "src"
TYPES = SRC / "types.rs"
OUT = ROOT / "docs" / "storage-key-inventory.md"

TIER_CALL = re.compile(r"\.storage\(\)\s*\.\s*(instance|persistent|temporary)\(\)")
KEY_REF = re.compile(r"DataKey::(\w+)")
LET_KEY = re.compile(r"let\s+(?:mut\s+)?(\w+)\s*(?::\s*DataKey)?\s*=\s*(?:&\s*)?DataKey::(\w+)")
WRITE_CALL = re.compile(r"\.\s*(set|extend_ttl)\s*\(")
LOOKBACK_LINES = 14
WINDOW_CHARS = 600


def parse_variants() -> dict[str, dict[str, str]]:
    """Return {variant: {"fields": "...", "doc": "..."}} in declaration order."""
    text = TYPES.read_text(encoding="utf-8")
    start = text.index("pub enum DataKey {")
    depth, i = 0, text.index("{", start)
    body_start = i + 1
    while True:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    body = text[body_start:i]

    variants: dict[str, dict[str, str]] = {}
    doc: list[str] = []
    for raw in body.splitlines():
        line = raw.strip()
        if line.startswith("///"):
            doc.append(line[3:].strip())
            continue
        if not line or line.startswith("//") or line.startswith("#["):
            continue
        m = re.match(r"(\w+)\s*(\([^)]*\))?\s*,?", line)
        if m:
            variants[m.group(1)] = {
                "fields": (m.group(2) or "").strip("()").replace(" ", ""),
                "doc": doc[0] if doc else "",
            }
        doc = []
    return variants


def is_test_file(path: Path) -> bool:
    return path.name.endswith("_tests.rs") or path.name.startswith("test") or path.name == "test.rs"


def scan() -> dict[str, dict[str, set[str]]]:
    """Return {variant: {tier: {files}}}."""
    found: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
    for path in sorted(SRC.rglob("*.rs")):
        if is_test_file(path) or path == TYPES:
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        text = "\n".join(lines)
        offsets = [0]
        for ln in lines:
            offsets.append(offsets[-1] + len(ln) + 1)

        def line_of(pos: int) -> int:
            lo, hi = 0, len(offsets) - 1
            while lo < hi:
                mid = (lo + hi + 1) // 2
                if offsets[mid] <= pos:
                    lo = mid
                else:
                    hi = mid - 1
            return lo

        for m in TIER_CALL.finditer(text):
            tier = m.group(1)
            window = text[m.end() : m.end() + WINDOW_CHARS]
            stmt = window.split(";", 1)[0]
            if not WRITE_CALL.search(stmt):
                continue
            keys = set(KEY_REF.findall(stmt))
            if not keys:
                # key passed by binding: `.set(&key, ..)` -> look back for its `let`.
                names = re.findall(r"&\s*(\w+)\b", stmt)
                lo = max(0, line_of(m.start()) - LOOKBACK_LINES)
                context = "\n".join(lines[lo : line_of(m.start()) + 1])
                for name, variant in LET_KEY.findall(context):
                    if name in names:
                        keys.add(variant)
            for k in keys:
                found[k][tier].add(path.name)
    return found


def render() -> str:
    variants = parse_variants()
    found = scan()
    out = [
        "# `DataKey` storage-key inventory",
        "",
        "Generated by `scripts/storage_key_inventory.py` from `contracts/price-oracle/src/types.rs`",
        "and the non-test contract sources. Do not edit by hand; re-run the script instead.",
        "",
        f"{len(variants)} variants. Tier is the Soroban storage class a variant is written to",
        "(`instance`, `persistent` or `temporary`). `unresolved` means no write could be",
        "attributed textually and the key needs a manual check.",
        "",
        "| Variant | Key fields | Tier(s) written | Written in | Description |",
        "|---|---|---|---|---|",
    ]
    counts: dict[str, int] = defaultdict(int)
    for name, info in variants.items():
        tiers = found.get(name, {})
        if tiers:
            tier_txt = ", ".join(f"`{t}`" for t in sorted(tiers))
            files = sorted({f for fs in tiers.values() for f in fs})
            files_txt = ", ".join(f"`{f}`" for f in files[:4]) + (" …" if len(files) > 4 else "")
            for t in tiers:
                counts[t] += 1
        else:
            tier_txt, files_txt = "unresolved", "—"
            counts["unresolved"] += 1
        fields = f"`{info['fields']}`" if info["fields"] else "—"
        desc = info["doc"].replace("|", "\\|")
        out.append(f"| `{name}` | {fields} | {tier_txt} | {files_txt} | {desc} |")
    out += ["", "## Summary", "", "| Tier | Variants |", "|---|---:|"]
    for t in ("instance", "persistent", "temporary", "unresolved"):
        out.append(f"| {t} | {counts.get(t, 0)} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    report = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != report:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/storage_key_inventory.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(report, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
